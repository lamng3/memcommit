"""Compare tier policies on an agent-shaped workload: how often is a memory an agent needs still in working memory?

python examples/policy_benchmark.py [--seed 0] [--out results]

Writes the reports to results/policies/<date>.json and the tables to
results/README.md, so every run lands in the results folder.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))  # run from a clone without installing

from mneme import ARC, FIFO, LFU, LRU, AccessCount, Forgetting, ImportanceAtLeast, Learned, Scored, TwoQueue
from mneme.bench import compare, synthetic

POLICIES = {
    "FIFO": lambda: (FIFO(), None),
    "LRU": lambda: (LRU(), None),
    "LFU": lambda: (LFU(), None),
    "Scored": lambda: (Scored(), None),
    "Forgetting": lambda: (Forgetting(), None),
    "2Q": lambda: (TwoQueue(), None),
    "ARC": lambda: (ARC(), None),
    "Learned": lambda: (Learned(), None),
    "LRU + promote used": lambda: (LRU(), AccessCount(3)),
    "Scored + promote important": lambda: (Scored(), ImportanceAtLeast(0.8)),
}
CAPACITIES = (16, 32, 64)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / "results", help="results folder (default: results/)")
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    events = synthetic(seed=args.seed)
    writes = sum(type(e).__name__ == "Write" for e in events)
    print(f"workload: {writes} writes, {len(events) - writes} uses (seed {args.seed})\n")
    reports = compare(events, POLICIES, CAPACITIES)
    print(
        f"{'policy':28} "
        + " ".join(f"{'cap ' + str(c):>9}" for c in CAPACITIES)
        + "   peak working, log records, ms (cap 32)"
    )
    for name in POLICIES:
        rows = [r for r in reports if r.policy == name]
        at32 = next(r for r in rows if r.capacity == 32)
        print(
            f"{name:28} "
            + " ".join(f"{r.hit_rate:9.3f}" for r in rows)
            + f"   {at32.peak_working}, {at32.records}, {at32.seconds * 1000:.0f}"
        )
    stamp = date.today().isoformat()
    raw = args.out / "policies" / f"{stamp}.json"
    raw.parent.mkdir(parents=True, exist_ok=True)
    data = {"seed": args.seed, "workload": "synthetic", "reports": [r.to_json() for r in reports]}
    raw.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    (args.out / "README.md").write_text(tables(reports, events, args.seed, raw.relative_to(args.out)), encoding="utf-8")
    print(f"\nwrote {raw} and {args.out / 'README.md'}")


def tables(reports: list, events: list, seed: int, raw: Path) -> str:
    """results/README.md: hit rate by capacity, then what each run cost, per capacity."""
    writes = sum(type(e).__name__ == "Write" for e in events)
    lines = [
        "# Results",
        "",
        "Generated by `python examples/policy_benchmark.py`; do not edit by hand.",
        f"Raw reports: [`{raw}`]({raw}).",
        "",
        "## Tier policies",
        "",
        f"Synthetic agent-shaped workload, seed {seed}: {writes} writes (60 tasks of 6 trace steps),",
        f"{len(events) - writes} skewed reuses of earlier memories, replayed through the real store.",
        "",
        "### Hit rate",
        "",
        "| Policy | " + " | ".join(f"cap {c}" for c in CAPACITIES) + " |",
        "|:--|" + ":--:|" * len(CAPACITIES),
    ]
    capped = [r for r in reports if "promote" not in r.policy]  # bold the best policy that stays within the cap
    best = {c: max(r.hit_rate for r in capped if r.capacity == c) for c in CAPACITIES}
    for name in POLICIES:
        cells = []
        for c in CAPACITIES:
            r = next(r for r in reports if r.policy == name and r.capacity == c)
            cells.append(f"**{r.hit_rate:.3f}**" if r in capped and r.hit_rate == best[c] else f"{r.hit_rate:.3f}")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Promotion policies hold more than the cap (see peak working memory below), so compare them",
        "with each other, not with the capped policies.",
        "",
        "### Cost",
        "",
        "Every miss is a page-in and usually an eviction; both are log records. No model calls: cost is",
        "log records written and replay time.",
    ]
    for c in CAPACITIES:
        lines += [
            "",
            f"#### cap {c}",
            "",
            "| Policy | Hits | Page-ins | Evictions | Promoted | Peak working | Log records | Replay ms |",
            "|:--|--:|--:|--:|--:|--:|--:|--:|",
        ]
        for name in POLICIES:
            r = next(r for r in reports if r.policy == name and r.capacity == c)
            lines.append(
                f"| {name} | {r.hits} | {r.paged_in} | {r.evicted} | {r.promoted} | {r.peak_working} "
                f"| {r.records:,} | {r.seconds * 1000:.0f} |"
            )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
